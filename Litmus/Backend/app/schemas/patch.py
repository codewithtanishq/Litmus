"""
CandidatePatch data contract for Swarm Debugger.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Optional
from uuid import uuid4
from pydantic import BaseModel, Field, ConfigDict


class AgentRole(str, Enum):
    """The role of an agent in the courtroom debate."""
    PROSECUTOR = "prosecutor"
    DEFENDER = "defender"
    JUDGE = "judge"


class CandidatePatch(BaseModel):
    """
    Candidate patch generated by an agent during a debugging round.

    Attributes:
        patch_id: Unique identifier for the proposed patch.
        agent_role: The role of the agent proposing this candidate (e.g. prosecutor or defender).
        proposed_code: The complete revised source code or unified patch.
        explanation: Natural language justification explaining the diagnosis and rationale.
        round_number: The debate round in which this patch was offered.
        diff: Optional unified diff showing exact changes from the original code.
        created_at: UTC timestamp when the patch was submitted.
    """

    model_config = ConfigDict(use_enum_values=True)

    patch_id: str = Field(
        default_factory=lambda: str(uuid4()),
        description="Unique identifier for this patch candidate.",
    )
    agent_role: AgentRole = Field(
        ...,
        description="Agent role proposing the fix (prosecutor or defender).",
    )
    proposed_code: str = Field(
        ...,
        min_length=1,
        description="The modified source code or complete patch.",
    )
    explanation: str = Field(
        ...,
        min_length=1,
        description="Detailed rationale and bug diagnosis behind the proposed patch.",
    )
    round_number: int = Field(
        default=1,
        ge=1,
        description="The round in which this patch was proposed.",
    )
    diff: Optional[str] = Field(
        default=None,
        description="Optional unified diff between original code and proposed code.",
    )
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp when the candidate patch was generated.",
    )
